# writes src/nfc.h, the tables Au's NFC (au_nfc) uses, from the
# Unicode Character Database in Python's unicodedata
# run: python3 -I support/nfc_table.py > src/nfc.h
import unicodedata as u

dec, comp = [], []
for c in range(0x110000):
    d = u.decomposition(chr(c))
    if not d or d.startswith('<'):
        continue
    parts = [int(x, 16) for x in d.split()]
    dec.append((c, parts[0], parts[1] if len(parts) > 1 else 0))
    # a primary composite: two parts, and NFC keeps it whole
    if len(parts) == 2 and u.normalize('NFC', chr(c)) == chr(c):
        comp.append((parts[0], parts[1], c))
comp.sort()

ccc, lo = [], None
for c in range(0x110001):
    k = u.combining(chr(c)) if c < 0x110000 else 0
    if lo is not None and (k != cur or c != prev + 1):
        ccc.append((lo, prev, cur))
        lo = None
    if k and lo is None:
        lo, cur = c, k
    prev = c

print('// generated by support/nfc_table.py from the Unicode')
print('// Character Database %s (Unicode license); do not edit'
      % u.unidata_version)
print('#define NFC_UNICODE "%s"' % u.unidata_version)
print('static const u32 nfc_decomp[][3] = {')
for r in dec:
    print('    { 0x%X, 0x%X, 0x%X },' % r)
print('};')
print('static const u32 nfc_comp[][3] = {')
for r in comp:
    print('    { 0x%X, 0x%X, 0x%X },' % r)
print('};')
print('static const u32 nfc_ccc[][3] = {')
for r in ccc:
    print('    { 0x%X, 0x%X, %d },' % r)
print('};')
